    private static final Pattern MINUTES = Pattern.compile("(\\d+) min ago"), HOURS = Pattern.compile("(\\d+) h ago"),
            DAYS = Pattern.compile("(\\d+) days ago"), TITLES = Pattern.compile("(\\d+) titles from the TV's apps, 3 new ones every hour\\."),
            SHELF = Pattern.compile("OK adds or removes \\(up to (\\d+)\\)\\. ← → change the order\\."),
            ON = Pattern.compile("Weatherglass TV is on: new home screen and screensaver, (\\d+) apps turned off\\.");

    /** Text built at runtime (a number inside): the same sentence in Indonesian, or the English as it is. */
    private static String pattern(String english) {
        Matcher m;
        if ((m = MINUTES.matcher(english)).matches()) return m.group(1) + " menit lalu";
        if ((m = HOURS.matcher(english)).matches()) return m.group(1) + " jam lalu";
        if ((m = DAYS.matcher(english)).matches()) return m.group(1) + " hari lalu";
        if ((m = TITLES.matcher(english)).matches()) return m.group(1) + " judul dari aplikasi TV, 3 baru setiap jam.";
        if ((m = SHELF.matcher(english)).matches()) return "OK menambah atau melepas (maks. " + m.group(1) + "). ← → mengubah urutan.";
        if ((m = ON.matcher(english)).matches()) return "Weatherglass TV aktif: layar utama dan screensaver baru, " + m.group(1) + " aplikasi dimatikan.";
        return english;
    }
